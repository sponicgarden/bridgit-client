// Generate the Apple adapter from the same trusted evaluator used by the registry.
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {practiceCatalog} from './practices.mjs';
export async function generatePracticeRuntime(root){
 const evaluator=(await readFile(path.join(root,'scripts/applet-practices.mjs'),'utf8')).replace(/^export /gm,'');
 const catalog=JSON.stringify(await practiceCatalog(root));
 const ui=await readFile(path.join(root,'public/shared/applet-ui.js'),'utf8');
 if((evaluator+catalog+ui).includes('"""#'))throw Error('Unsafe Swift string delimiter');
 const swift='// Generated by builder-recipes.mjs from the public contract.\nimport Foundation\npublic enum AppletPracticeSource {\n static let engine = #"""\n'+evaluator+'\nconst catalog = '+catalog+';\n"""#\n public static let webUI = #"""\n'+ui+'\n"""#\n}\n';
 await writeFile(path.join(root,'../apple/BridgitAppletRuntime/Sources/BridgitAppletRuntime/AppletPracticeSource.swift'),swift);
}
